// Additive registry schema 7. Reproduce only the planned joint capacity
// replacements; old table/foreign-key/immutable definitions stay historical.
import { writeFileSync } from 'node:fs';

const old = [
  ['confirmation_batches', 'batch_id', 'document_json'],
  ['confirmation_selections', 'selection_id', 'document_json'],
  ['confirmation_operations', 'operation_id', 'document_json'],
  ['confirmation_exposures', 'exposure_id', 'document_json'],
  ['confirmation_admissions', 'admission_id', 'document_json'],
  ['confirmation_events', 'event_id', 'document_json'],
  ['confirmation_blobs', 'blob_sha256', 'content_bytes'],
  ['confirmation_conflicts', 'conflict_id', 'document_json'],
];
const table = 'confirmation_source_witnesses';
const all = [...old, [table, 'witness_sha256', 'content_bytes']];
const rows = all.map(([name]) => `(SELECT COUNT(*) FROM ${name})`).join(' + ');
const byteExpr = column => column === 'document_json' ? 'length(CAST(document_json AS BLOB))' : 'length(content_bytes)';
const bytes = all.map(([name, , column]) => `(SELECT COALESCE(SUM(${byteExpr(column)}),0) FROM ${name})`).join(' + ');
const capacity = ([name, id, column]) => `CREATE TRIGGER ${name}_capacity BEFORE INSERT ON ${name}
WHEN NOT EXISTS (SELECT 1 FROM ${name} WHERE ${id} = NEW.${id})
 AND ((${rows}) >= 10000 OR (${bytes}) + ${column === 'document_json' ? 'length(CAST(NEW.document_json AS BLOB))' : 'length(NEW.content_bytes)'} > 67108864)
BEGIN SELECT RAISE(ABORT, 'confirmation history capacity exceeded'); END;`;
const sql = `-- P13c-3b-1b-2b-1. Generated by scripts/generate-source-witness-migration.mjs.
-- Keep migration 0006, old blob bytes/FKs and birth metadata unchanged.
-- Rust performs bounded original provenance backfill in this same migration TX.
CREATE TABLE ${table} (
    witness_sha256 TEXT NOT NULL CHECK (typeof(witness_sha256) = 'text' AND length(witness_sha256) = 64 AND length(CAST(witness_sha256 AS BLOB)) = 64 AND witness_sha256 NOT GLOB '*[^0-9a-f]*') PRIMARY KEY,
    byte_length INTEGER NOT NULL CHECK (typeof(byte_length) = 'integer' AND byte_length BETWEEN 1 AND 8388608),
    content_bytes BLOB NOT NULL CHECK (typeof(content_bytes) = 'blob' AND length(content_bytes) = byte_length),
    recorded_at TEXT NOT NULL CHECK (typeof(recorded_at) = 'text')
);
CREATE TRIGGER ${table}_no_update BEFORE UPDATE ON ${table}
BEGIN SELECT RAISE(ABORT, 'confirmation_source_witnesses is append-only'); END;
CREATE TRIGGER ${table}_no_delete BEFORE DELETE ON ${table}
BEGIN SELECT RAISE(ABORT, 'confirmation_source_witnesses is append-only'); END;
CREATE TRIGGER ${table}_no_replacement BEFORE INSERT ON ${table}
WHEN EXISTS (SELECT 1 FROM ${table} WHERE witness_sha256 = NEW.witness_sha256 AND NOT (witness_sha256 IS NEW.witness_sha256 AND byte_length IS NEW.byte_length AND content_bytes IS NEW.content_bytes AND recorded_at IS NEW.recorded_at))
BEGIN SELECT RAISE(ABORT, 'confirmation_source_witnesses is append-only'); END;

-- A digest has exactly one logical blob kind across both physical tables.
CREATE TRIGGER confirmation_source_witnesses_blob_namespace BEFORE INSERT ON ${table}
WHEN EXISTS (SELECT 1 FROM confirmation_blobs WHERE blob_sha256 = NEW.witness_sha256)
BEGIN SELECT RAISE(ABORT, 'confirmation blob namespace collision'); END;
CREATE TRIGGER confirmation_blobs_witness_namespace BEFORE INSERT ON confirmation_blobs
WHEN EXISTS (SELECT 1 FROM ${table} WHERE witness_sha256 = NEW.blob_sha256)
BEGIN SELECT RAISE(ABORT, 'confirmation blob namespace collision'); END;

-- Only replace the eight old joint capacity triggers. Interval/unknown caps
-- and all original append-only/FK/domain guards remain in force.
${old.map(([name]) => `DROP TRIGGER ${name}_capacity;`).join('\n')}

${all.map(capacity).join('\n\n')}
`;
writeFileSync(new URL('../src-tauri/registry_migrations/0007_confirmation_source_witness.sql', import.meta.url), sql);
